BODY = '''<p>The bathroom has wet floors, hard surfaces and moments when you stand up from a low seat. The CDC says more than 1 in 4 older adults falls each year and that a single fall doubles the chance of another. Two public sources, the CDC's "Check for Safety" checklist and MedlinePlus's "Bathroom safety for adults" page, give a short list of fixes. Here they are as seven checks you can do in one afternoon.</p>

<h2>The Seven Checks</h2>
<ol class="steps">
<li><strong>Mat in the tub.</strong> MedlinePlus suggests non-slip suction mats or rubber silicone decals in the bottom of the tub. The CDC suggests a non-slip rubber mat or self-stick strips on a slippery tub or shower floor.</li>
<li><strong>Mat outside the tub.</strong> MedlinePlus says to use a non-skid bath mat outside the tub for firm footing.</li>
<li><strong>Two grab bars.</strong> One helps you get in and out of the tub, and one helps you stand from a seated position. MedlinePlus says to fix them to the wall vertically or horizontally, not diagonally, and the CDC adds one next to the toilet. See our <a href="/best-grab-bars/">grab bar guide</a>.</li>
<li><strong>A seat in the shower.</strong> MedlinePlus advises sitting on a bath chair or bench when you shower. See our <a href="/best-shower-chairs/">shower chair guide</a>.</li>
<li><strong>A higher toilet seat.</strong> MedlinePlus says raising the toilet seat height can help prevent falls, with a raised seat or a commode chair. See our <a href="/best-raised-toilet-seats/">raised toilet seat guide</a>.</li>
<li><strong>A lit path.</strong> The CDC suggests a lamp close to the bed and a nightlight on the path from the bed to the bathroom.</li>
<li><strong>Water temperature.</strong> MedlinePlus says to set the water heater to no more than 120°F (49°C) to prevent burns.</li>
</ol>

<h2>Why Each Check Helps</h2>
<p>Mats give your feet something to grip on a surface that is slippery when wet. Grab bars give your hands a fixed point when your feet are not enough. A shower seat removes the need to stand while you wash, and a higher toilet seat shortens the distance you have to lower yourself and push back up.</p>
<p>The light and the water temperature are less obvious. A dark path is a place to trip, and the CDC lists it for that reason. A water heater set no higher than 120°F protects you from burns if you cannot move away quickly.</p>

<h2>What Not to Rely On</h2>
<p>MedlinePlus is direct about one thing: "Do not use towel racks as grab bars. They can't support your weight." A towel rack, a soap dish or the edge of a sink is not a substitute. Grab bars have to be fixed into the wall behind the tile, which usually means a stud, and the makers' load ratings depend on that.</p>
<p>A raised seat or a shower chair makes a task easier, but neither replaces a grab bar. The handles on a raised toilet seat are not fixed to the wall, and a shower chair does not help you step into the tub.</p>

<h2>When to Ask for Help</h2>
<p>The CDC notes that fewer than half of older adults who fall tell their doctor. If you have fallen, almost fallen or feel unsteady getting up from the toilet, say so. A doctor or an occupational therapist can look at your bathroom and your movements and tell you which of these changes will help most.</p>

<h2>Where to Start</h2>
<p>If you do only two things, fit a non-slip mat in the tub and fix a grab bar at the tub's edge into a stud. Then add a shower chair and a higher toilet seat if standing up is hard. Our guides compare the options: <a href="/best-grab-bars/">grab bars</a>, <a href="/best-shower-chairs/">shower chairs</a> and <a href="/best-raised-toilet-seats/">raised toilet seats</a>.</p>'''

